"""The invariants (r, a, δ) of the even hyperbolic 2-elementary lattices in L_K3.

The seven conditions are Nikulin's. "Integral symmetric bilinear forms and some of
their applications", Math. USSR Izvestija 14 (1980), Theorem 3.6.2, p. 144 (PDF page
43), states them for an even 2-elementary lattice with invariants (δ; t+, t-, a); the
same seven are restated as Theorem 4.3.1, p. 1427 of "Factor groups of groups of
automorphisms of hyperbolic forms with respect to subgroups generated by 2-reflections",
J. Soviet Math. 22 (1983) 1401-1475, where the scan's text layer is complete:

  1) a ≤ t+ + t-
  2) a + t+ + t- ≡ 0 (mod 2)
  3) t+ - t- ≡ 0 (mod 4), if δ = 0
  4) t+ - t- ≡ ±a (mod 8), if a ≤ 1
  5) δ = 0, if a = 0
  6) δ = 0, if a = 2 and t+ - t- ≡ 4 (mod 8)
  7) t+ - t- ≡ 0 (mod 8), if a = t+ + t- and δ = 0

A hyperbolic lattice of rank r has signature (1, r - 1), so t+ = 1 and t- = r - 1. It
embeds primitively in the even unimodular lattice L_K3 of signature (3, 19) exactly
when its orthogonal complement exists: by Corollary 1.12.3, p. 122 (PDF page 21), that
is an even lattice with invariants (l+ - t+, l- - t-, -q), and -q of a 2-elementary
form is 2-elementary with the same (a, δ), so the condition is 1)-7) for
(δ; 2, 20 - r, a).

The count of the enumeration is the check of this transcription: Alexeev and Engel,
"Modular compactifications and the Cox ring of Enriques surfaces" (arXiv:2208.10383),
§1, "there are 75 cases". It is a check and never a value a card carries.
"""

from typing import Iterator


def exists(times_plus: int, times_minus: int, a: int, delta: int) -> bool:
    """Whether an even 2-elementary lattice with these invariants exists: conditions 1)-7)."""
    difference = times_plus - times_minus
    if a > times_plus + times_minus:  # 1)
        return False
    if (a + times_plus + times_minus) % 2 != 0:  # 2)
        return False
    if delta == 0 and difference % 4 != 0:  # 3)
        return False
    if a <= 1 and difference % 8 not in {(a % 8), (-a) % 8}:  # 4)
        return False
    if a == 0 and delta != 0:  # 5)
        return False
    if a == 2 and difference % 8 == 4 and delta != 0:  # 6)
        return False
    if a == times_plus + times_minus and delta == 0 and difference % 8 != 0:  # 7)
        return False
    return True


def triples() -> Iterator[tuple[int, int, int]]:
    """Each (r, a, δ) of an even hyperbolic 2-elementary lattice lying primitively in L_K3."""
    for rank in range(1, 23):
        for a in range(0, rank + 1):
            for delta in (0, 1):
                if exists(1, rank - 1, a, delta) and exists(2, 20 - rank, a, delta):
                    yield rank, a, delta


def test_the_enumeration_is_the_75_classes_of_alexeev_engel() -> None:
    """The count is the check of the transcription (arXiv:2208.10383, §1: "there are 75 cases")."""
    found = list(triples())
    assert len(found) == 75, f"{len(found)} triples, not 75"
    assert len(set(found)) == len(found)
    assert all(1 <= rank <= 20 for rank, _a, _delta in found)
    assert sorted(rank for rank, _a, _delta in found) == sorted(
        [1] + [2] * 3 + [3] * 2 + [4] * 2 + [5] * 2 + [6] * 4 + [7] * 3 + [8] * 4 + [9] * 5 + [10] * 11 + [11] * 6
        + [12] * 5 + [13] * 4 + [14] * 6 + [15] * 3 + [16] * 3 + [17] * 3 + [18] * 5 + [19] * 2 + [20]
    )


if __name__ == "__main__":
    for triple in triples():
        print(triple)
