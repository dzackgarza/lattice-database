r"""#43: the reflection subgroup of the cusp stabilizer does not move the root classes, at any cusp.

$W_v \leq G_v$ is generated by the reflections $\sigma_w$ in the walls of the chamber at the cusp --- every wall is
orthogonal to $v$, so every $\sigma_w$ fixes $v$ --- and `root_class_orbits` applies only the reflections of the
classes it is given, that is the $(-2)$-walls.  So the chamber's own walls are the largest part of the stabilizer
this repository can construct, and this probe asks whether it moves a root class at all.

Two facts are computed, and neither needs the generating family that a primitive isotropic line withholds:

1. **No short word moves one.**  The orbit of a root class under the walls' reflections is walked breadth first; the
   walk is on classes, so it is complete up to its depth, and a ball of a few hundred classes is the whole ball.
2. **No word moves one, by the diagram.**  In a Coxeter system conjugate standard parabolics are equal, and the
   setwise stabilizer of the mirror of a wall is the parabolic generated by that wall and by the walls *orthogonal*
   to it.  So two walls in one $W_v$-orbit have the same orthogonal neighbour set.  The root walls of every cusped
   row have pairwise different sets, so they are in different $W_v$-orbits.

That is what closes the question for this repository: the orbit count is not undecided because the search was too
shallow, but because the constructible part of $\Gamma_v$ provably cannot identify the classes, and the rest of
$\Gamma_v$ is what `generation_obstruction()` names (sage-extensions#312).

    sage results/probe-43-wv-orbits.py
"""

from math import gcd

import yaml
from sage.all import ZZ, matrix, vector

CARD = "lattices/029J.md"
DEPTH = 12
CAP = 1000000

metadata = yaml.safe_load(open(CARD).read().split("---")[1])
gram = matrix(ZZ, metadata["gram_tensor"])
rows = metadata["integral"]["cusp_chambers"]["gamma-en-2"]


def square(x) -> int:
    return int(vector(ZZ, x) * gram * vector(ZZ, x))


def boundary_lattice(cusp):
    eta = vector(ZZ, cusp)
    kernel = matrix(ZZ, [gram * eta]).right_kernel_matrix()
    c = vector(ZZ, [ZZ(entry) for entry in eta * kernel.transpose() * (kernel * kernel.transpose()).inverse()])
    assert gcd(*[abs(int(entry)) for entry in c]) == 1
    left = matrix(ZZ, [c]).transpose().smith_form()[1]
    unimodular = left.inverse().transpose()
    assert vector(ZZ, list(unimodular[0])) in (c, -c)
    basis = (unimodular * kernel)[1:]
    return basis, basis * gram * basis.transpose()


for row in rows[2:5]:
    basis, gram_k = boundary_lattice(row["cusp"])
    names = [wall["name"] for wall in row["walls"]]
    walls = []
    for wall in row["walls"]:
        x = vector(ZZ, wall["vector"])
        walls.append(vector(ZZ, [ZZ(entry) for entry in gram_k.solve_right(vector(ZZ, [int(b * gram * x) for b in basis.rows()]))]))
    pairings = [[int(a * gram_k * b) for b in walls] for a in walls]
    roots = [index for index in range(len(walls)) if pairings[index][index] == -2]
    reflections = [(walls[index], pairings[index][index]) for index in range(len(walls))]

    def apply(reflection, x):
        wall, denominator = reflection
        return x - ZZ(2 * int(x * gram_k * wall) // denominator) * wall

    found = []
    for index in roots[1:]:
        visited = {tuple(walls[roots[0]])}
        frontier = [walls[roots[0]]]
        hit = None
        for depth in range(1, DEPTH + 1):
            following = []
            for state in frontier:
                for reflection in reflections:
                    image = apply(reflection, state)
                    key = tuple(image)
                    if key in visited:
                        continue
                    if key == tuple(walls[index]):
                        hit = depth
                        break
                    visited.add(key)
                    following.append(image)
                if hit is not None or len(visited) > CAP:
                    break
            frontier = following
            if hit is not None or not frontier:
                break
        invariant = frozenset(j for j in range(len(walls)) if j != roots[0] and pairings[roots[0]][j] == 0)
        other = frozenset(j for j in range(len(walls)) if j != index and pairings[index][j] == 0)
        found.append((names[index], hit, invariant == other))

    print(f"{row['statement']:>7} p.{row['printed_page']:>2}  root walls {[names[i] for i in roots]}", flush=True)
    for name, hit, same in found:
        print(f"        {names[roots[0]]} -> {name}: word length {hit} (None = none within depth {DEPTH}), "
              f"orthogonal neighbour sets equal: {same}", flush=True)
