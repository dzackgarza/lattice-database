"""The cardinality of `H_e`, computed from the nine self-isometries the card of `0125` stores (lattice-database#40).

`arithmetic-groups/h-e.md` states `H_e` as the subgroup of `G_e` generated by nine stored
self-isometries of `L = U(2) + E8(-2)`, and states its cardinality. That value was `aleph0` with no
source and no certificate; this program decides it from the stored matrices and the card's Gram
tensor alone, so the card can cite a completed computation instead of asserting a value.

What is computed, exactly and without the preamble:

* each of the nine matrices preserves the Gram tensor and is unimodular;
* each has the characteristic polynomial `(x - 1)^9 (x + 1)`, so each is a reflection, fixing a
  hyperplane and negating one line; that line's primitive vector `v` is read off the kernel of
  `M + 1`;
* every `v` has `(v, v) = -4`, and the pairings `(v_i, v_j)` are `0` or `2`, so the Cartan matrix
  `A_ij = 2 (v_i, v_j) / (v_j, v_j)` is `2` on the diagonal and `-1` or `0` off it;
* the diagram of that Cartan matrix is `E_8` (arms of length 1, 2 and 4 at the branch node) and one
  isolated node, and the matrix is positive definite (every leading principal minor is positive);
* the reflections of a positive definite diagram generate exactly its Coxeter group (Tits: the
  geometric representation of a Coxeter group is faithful), so the eight `E_8` reflections generate
  `W(E_8)`. Its order is computed here, not quoted: the reflections are turned into permutations of
  the set of `240` vectors of norm `-4` in their span — the `W(E_8)` orbit of a root — and the
  permutation group's order is `696729600`;
* the isolated node's reflection fixes every `E_8` root, so it commutes with all of them and is not
  among them; it contributes its own factor of `2`, which is the kernel of `rho_L` on `H_e`
  (`|rho_L(H_e)| = 696729600` is the engine's own order of `P`, already certified for
  `arithmetic-group.h-e.generator_morphisms`).

So `|H_e| = 2 * 696729600 = 1393459200`, finite. The run prints it.
"""

from __future__ import annotations

import itertools
from fractions import Fraction
from pathlib import Path

import frontmatter
import sympy as sp
from sympy.combinatorics import Permutation, PermutationGroup

ROOT = Path(__file__).resolve().parent.parent
TAG = "0125"
SLUG = "h-e"


def card():
    document = frontmatter.load(str(ROOT / "lattices" / f"{TAG}.md"))
    group = frontmatter.load(str(ROOT / "arithmetic-groups" / f"{SLUG}.md"))
    return document.metadata, group.metadata


def preserves(matrix: sp.Matrix, gram: sp.Matrix) -> bool:
    return matrix.T * gram * matrix == gram


def primitive(vector: sp.Matrix) -> sp.Matrix:
    """The primitive integer vector on the line `vector` spans."""
    rational = [sp.nsimplify(entry) for entry in vector]
    scale = sp.ilcm(*[sp.denom(entry) for entry in rational])
    integral = [sp.Integer(entry * scale) for entry in rational]
    divisor = sp.gcd([abs(int(entry)) for entry in integral])
    return sp.Matrix([entry / divisor for entry in integral])


def main() -> None:
    metadata, group = card()
    gram = sp.Matrix([[sp.Rational(str(entry)) for entry in row] for row in metadata["gram_tensor"]])
    by_name = {morphism["name"]: morphism for morphism in metadata["morphisms"]}
    names = list(group["data"]["generator_morphisms"])
    assert len(names) == 9, names

    X = sp.Symbol("x")
    matrices = [sp.Matrix(by_name[name]["matrix"]) for name in names]
    identity = sp.eye(gram.rows)
    roots = []
    for name, matrix in zip(names, matrices, strict=True):
        assert preserves(matrix, gram), f"{name} does not preserve the form"
        assert abs(matrix.det()) == 1, f"{name} is not unimodular"
        assert sp.factor(matrix.charpoly(X).as_expr()) == sp.factor((X - 1) ** 9 * (X + 1)), name
        assert (matrix * matrix - identity) == sp.zeros(gram.rows), f"{name} is not an involution"
        line = (matrix + identity).nullspace()
        assert len(line) == 1, f"{name} does not negate a line"
        vector = primitive(line[0])
        assert (vector.T * gram * vector)[0] == -4, f"{name} is not a reflection in a vector of norm -4"
        roots.append(vector)
    print(f"nine reflections, root norms {sorted({int((v.T * gram * v)[0]) for v in roots})}")

    pairing = sp.Matrix(9, 9, lambda i, j: (roots[i].T * gram * roots[j])[0])
    cartan = sp.Matrix(9, 9, lambda i, j: sp.Integer(2) if i == j else sp.Integer(2) * pairing[i, j] / pairing[j, j])
    assert all(int(entry) in (2, 0, -1) for entry in cartan), cartan
    edges = [(i, j) for i in range(9) for j in range(9) if i < j and cartan[i, j] == -1]
    print("edges (by position in the generator list):", [(names[i], names[j]) for i, j in edges])

    # Positive definite: every leading principal minor is positive.
    minors = [sp.Matrix(cartan[: size, : size]).det() for size in range(1, 10)]
    assert all(minor > 0 for minor in minors), minors
    print("leading principal minors:", [int(minor) for minor in minors])

    # The diagram: connected components, and the arms at each node of degree 3.
    neighbours = {index: set() for index in range(9)}
    for i, j in edges:
        neighbours[i].add(j)
        neighbours[j].add(i)
    components = []
    unseen = set(range(9))
    while unseen:
        start = unseen.pop()
        seen, queue = {start}, [start]
        while queue:
            node = queue.pop()
            for other in neighbours[node]:
                if other not in seen:
                    seen.add(other)
                    unseen.discard(other)
                    queue.append(other)
        components.append(sorted(seen))
    print("components:", [[names[index] for index in component] for component in components])

    # The E_8 component: eight nodes, one of degree 3, arms of length 1, 2 and 4.
    e8, other = sorted(components, key=len, reverse=True)
    assert (len(e8), len(other)) == (8, 1), components
    branch = next(index for index in e8 if len(neighbours[index]) == 3)

    def arm(start: int) -> int:
        previous, length = branch, 0
        while True:
            length += 1
            next_node = next((node for node in neighbours[start] if node != previous), None)
            if next_node is None:
                return length
            previous, start = start, next_node

    arms = sorted(arm(node) for node in neighbours[branch])
    assert arms == [1, 2, 4], arms
    print(f"E_8: branch at {names[branch]}, arms of length {arms}; plus the isolated node {names[other[0]]}")

    # The E_8 order, computed: the eight reflections are permutations of the 240 roots of their span.
    e8_reflections = [matrices[index] for index in e8]
    orbit = {tuple(roots[e8[0]])}
    frontier = [roots[e8[0]]]
    while frontier:
        following = []
        for vector in frontier:
            for matrix in e8_reflections:
                image = matrix * vector
                if image.T * gram * image != sp.Matrix([[-4]]):
                    continue
                key = tuple(int(entry) for entry in image)
                if key not in orbit:
                    orbit.add(key)
                    following.append(image)
        frontier = following
    roots_of_e8 = sorted(orbit)
    position = {key: number for number, key in enumerate(roots_of_e8)}
    print("roots of the E_8 span:", len(roots_of_e8))
    assert len(roots_of_e8) == 240, len(roots_of_e8)
    generators = []
    for matrix in e8_reflections:
        images = [matrix * sp.Matrix(key) for key in roots_of_e8]
        generators.append(Permutation([position[tuple(int(entry) for entry in image)] for image in images]))
    order = PermutationGroup(generators).order()
    print("order of the group the eight E_8 reflections generate:", order)
    assert order == 696729600, order

    # The isolated reflection fixes every root of the E_8 span and negates its own line: a direct factor.
    isolated = other[0]
    assert all((matrices[isolated] * sp.Matrix(key)).equals(sp.Matrix(key)) for key in roots_of_e8)
    assert (matrices[isolated] * roots[isolated]).equals(-roots[isolated])

    cardinality = 2 * order
    print(f"|H_e| = 2 * {order} = {cardinality}")


if __name__ == "__main__":
    main()
