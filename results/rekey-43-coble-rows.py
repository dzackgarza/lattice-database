"""#43: key the two Coble rows to `gamma-co-2`, now that the card exists, and say what the transporter order is.

The decision of 2026-11-19 stored the two one-class rows under the standard subgroup `O` because there was no card for
the Coble group. The card exists now (`arithmetic-groups/gamma-co-2.md`), so the rows belong under the group whose cusps
they are: their count is one whatever the subgroup, and the key should name the right group.

The certificate text is rewritten to say what the transporter order is: the order of the cyclic group generated by the
symmetry the row's proof exhibits, acting on the orbit — 1 for a one-class orbit, 2 for the two-class rows, computed as
a full cycle of the exhibited symmetry on the classes (`tests/test_cusp_root_orbits.py` asserts it).

    .scratch/wt43ag-run.sh -u results/rekey-43-coble-rows.py            # check, write nothing
    .scratch/wt43ag-run.sh -u results/rekey-43-coble-rows.py --write    # re-key and certify
"""

import sys
from pathlib import Path

from latticedb import certificates, corpus, genus, records, storage
from latticedb.model import Lattice

ROOT = Path("/repo")
TAG = "6JRR"
CARD = ROOT / "lattices" / f"{TAG}.md"

document = corpus.read_card(CARD)
metadata = corpus.front_matter(document)
block = dict(metadata["integral"])
fields = dict(block["cusp_root_orbits"])
moved = fields.pop("O", [])
fields["gamma-co-2"] = moved
block["cusp_root_orbits"] = {key: fields[key] for key in sorted(fields)}
metadata["integral"] = block
lattice = Lattice.model_validate(metadata)
print("keys:", {key: [row["statement"] for row in value] for key, value in block["cusp_root_orbits"].items()})
computation = genus.name(TAG, "cusp_root_orbits", lattice.definiteness)
digest = certificates.certification_hash(computation, lattice, genus.certified_value("cusp_root_orbits", block["cusp_root_orbits"], lattice))
print("new hash:", digest)

if "--write" not in sys.argv[1:]:
    print("dry run: nothing written")
    raise SystemExit(0)

BY = (
    'H. Sterk, "Compactifications of the period space of Enriques surfaces, Part I", Math. Z. 207 (1991), 1-36: '
    "(4.3.7), p. 22, prints the chamber at e' + f' + bar_alpha_8 and (4.3.8), p. 23, the chamber at 2e' + f' + bar_alpha_1. "
    "T_Co is delta^perp for delta = e - f, so a wall of a chamber is a wall of T_Co exactly when it is orthogonal to "
    "delta; of the walls that are, exactly one at each cusp is orthogonal to the cusp and of square -2, so the cusp's "
    "root family in K_I = v^perp/Zv is a single class and its orbits are one orbit under every subgroup. The rows are "
    "keyed to gamma-co-2, the group those cusps belong to, whose values are certified on this card. transporter_order is "
    "the order of the cyclic group the row's proof exhibits acting on the orbit: 1 for a one-class orbit, whose exhibited "
    "transporter is the identity. results/store-43-coble-rows.py writes the rows and results/rekey-43-coble-rows.py "
    "keys them here"
)
metadata["certifications"] = {**lattice.certifications, "integral.cusp_root_orbits": digest}
storage.write_text(CARD, records.record_text(metadata, document.content))
held = certificates.load(ROOT, tags=(TAG,))
held[computation] = certificates.Certificate(hash=digest, by=BY)
certificates.save(ROOT, held, tags=(TAG,))
print(f"stored; {computation} = {digest}")
